export function Conclusions({ version, rows, stats }) {
  const has = rows.length > 0 && Number.isFinite(stats.tMean)
  const isPrint = version === 'print'
  return (
    <>
      <h3>Вывод</h3>
      {has ? (
        <div className="conclusion-text">
          <p>
            По результатам {rows.length} измерений времени падения груза с высоты{' '}
            <Tex>{String.raw`h = ${fmt(stats.h, 2)}`}</Tex> м найдено среднее время{' '}
            <Tex>{String.raw`\bar t = ${fmt(stats.tMean, 3)}`}</Tex> со средней абсолютной
            погрешностью <Tex>{String.raw`\Delta t = ${fmt(stats.dT, 4)}`}</Tex> с; относительная
            погрешность составляет <Tex>{String.raw`\delta_t = ${fmt(stats.dtRel, 1)}\%`}</Tex>.
          </p>
          <p>Вычислены кинематические характеристики движения груза и точки обода шкива:</p>
          <Eq>
            {String.raw`a = (${fmt(stats.a, 3)} \pm ${fmt(stats.da, 3)})\ \text{м/с}^2,\qquad v = (${fmt(stats.v, 2)} \pm ${fmt(stats.dv, 2)})\ \text{м/с}`}
          </Eq>
          <Eq>
            {String.raw`\omega = (${fmt(stats.w, 2)} \pm ${fmt(stats.dw, 2)})\ \text{рад/с},\qquad \varepsilon = (${fmt(stats.eps, 2)} \pm ${fmt(stats.deps, 2)})\ \text{рад/с}^2`}
          </Eq>
          <Eq>
            {String.raw`a_{\tau} = (${fmt(stats.at, 3)} \pm ${fmt(stats.dat, 3)})\ \text{м/с}^2,\qquad a_n = (${fmt(stats.an, 2)} \pm ${fmt(stats.dan, 2)})\ \text{м/с}^2,\qquad a_0 = (${fmt(stats.a0, 2)} \pm ${fmt(stats.da0, 2)})\ \text{м/с}^2`}
          </Eq>
          <p>
            Движение груза является равноускоренным: ускорение <Tex>{String.raw`a`}</Tex> постоянно,
            а нормальная составляющая ускорения точки обода <Tex>{String.raw`a_n`}</Tex> растёт с
            увеличением скорости.
          </p>
        </div>
      ) : (
        <div className="tbl-empty">Выполните измерения на вкладке «Эксперимент» — вывод будет сформирован автоматически.</div>
      )}

      <h3>{isPrint ? 'Контрольные вопросы (очная методичка)' : 'Контрольные вопросы'}</h3>
      <div className="qa">
        <details>
          <summary>1. Дайте определение материальной точки.</summary>
          <div className="qa-body">
            <p>
              Материальная точка — тело, размерами которого в условиях данной задачи можно
              пренебречь. Это модель, при которой тело заменяется точкой, обладающей массой тела, но
              не имеющей размеров. В настоящей работе груз при поступательном движении можно
              рассматривать как материальную точку.
            </p>
          </div>
        </details>
        <details>
          <summary>2. Дайте определения векторов скорости и ускорения. Чем они отличаются от средних?</summary>
          <div className="qa-body">
            <p>
              Мгновенная скорость <Tex>{String.raw`\vec v = d\vec r/dt`}</Tex> — первая производная
              радиус-вектора по времени; она направлена по касательной к траектории. Средняя скорость{' '}
              <Tex>{String.raw`\vec v_{\text{ср}} = \Delta \vec r/\Delta t`}</Tex> направлена вдоль
              вектора перемещения и совпадает с мгновенной только при равномерном движении.
              Мгновенное ускорение <Tex>{String.raw`\vec a = d\vec v/dt`}</Tex> характеризует быстроту
              изменения скорости и направлено по изменению вектора скорости; среднее ускорение{' '}
              <Tex>{String.raw`\vec a_{\text{ср}} = \Delta \vec v/\Delta t`}</Tex> — по изменению
              скорости за конечный интервал.
            </p>
          </div>
        </details>
        <details>
          <summary>3. Что такое поступательное и вращательное движение?</summary>
          <div className="qa-body">
            <p>
              Поступательное — движение, при котором любая прямая, жёстко связанная с телом, остаётся
              параллельной самой себе; все точки тела движутся одинаково. Вращательное — движение, при
              котором все точки тела описывают окружности вокруг общей оси. Груз в работе совершает
              поступательное движение, а маховик (шкив) — вращательное.
            </p>
          </div>
        </details>
        {!isPrint && (
          <details>
            <summary>4. В чём отличие нормального и тангенциального ускорения?</summary>
            <div className="qa-body">
              <p>
                Тангенциальное ускорение <Tex>{String.raw`a_{\tau}`}</Tex> направлено по касательной к
                траектории и изменяет модуль скорости. Нормальное (центростремительное) ускорение{' '}
                <Tex>{String.raw`a_n = v^2/R`}</Tex> направлено к центру кривизны и изменяет
                направление скорости. Полное ускорение{' '}
                <Tex>{String.raw`a_0 = \sqrt{a_{\tau}^2 + a_n^2}`}</Tex>.
              </p>
            </div>
          </details>
        )}
      </div>
    </>
  )
}
